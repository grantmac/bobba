import {beforeEach,afterEach,describe,it,expect,vi} from 'vitest';
import {convexTest} from 'convex-test';
import schema from '../convex/schema.js';
import {api,internal} from '../convex/_generated/api.js';
const modules=import.meta.glob('../convex/**/*.js');
const token='a'.repeat(64),other='b'.repeat(64);
const look={hair:{model:'1',color:'#624631'},skin:{model:'1',color:'#e8b18a'},top:{model:'1',color:'#6b8c64'},bottom:{model:'1',color:'#55677e'},shoes:{model:'1',color:'#42454c'}};
let t,agentToken,player,spaceId;
beforeEach(async()=>{t=convexTest(schema,modules);player=await t.mutation(api.room.join,{token,name:'Host',look});({agentToken}=await t.mutation(api.agents.createKey,{token}));const space=await t.mutation(api.agents.addSpace,{agentToken,name:'Games'});spaceId=space.id??space.spaceId;await t.run(ctx=>ctx.db.patch(player.id,{zone:spaceId,route:[{x:23.5,z:3.5}]}));});
afterEach(()=>vi.restoreAllMocks());
const quiz=()=>t.mutation(api.activities.create,{agentToken,spaceId,name:'Quiz',kind:'quiz',durationSeconds:60,questions:[{prompt:'Two plus two?',options:['3','4'],answer:1}]});
describe('shared room activities',()=>{
  it('releases a wrong-answer buzzer, prevents repeat attempts, and ignores an old expiry after a new round',async()=>{
    const {id}=await quiz();
    await t.mutation(api.activities.play,{token,activityId:id,action:'join'});
    await t.mutation(api.activities.control,{token,activityId:id,action:'start'});
    await t.mutation(api.activities.play,{token,activityId:id,action:'buzz',round:1});
    expect(await t.mutation(api.activities.play,{token,activityId:id,action:'answer',round:1,choice:0})).toEqual({correct:false});
    expect((await t.query(api.activities.list,{token,spaceId}))[0].buzzer).toBeNull();
    await expect(t.mutation(api.activities.play,{token,activityId:id,action:'buzz',round:1})).rejects.toThrow('already');
    await t.mutation(api.activities.control,{token,activityId:id,action:'finish'});
    await t.mutation(api.activities.control,{token,activityId:id,action:'start'});
    await t.mutation(internal.activities.expire,{activityId:id,round:1});
    expect((await t.query(api.activities.list,{token,spaceId}))[0].status).toBe('playing');
    vi.spyOn(Date,'now').mockReturnValue(Date.now()+61000);
    await t.mutation(internal.activities.expire,{activityId:id,round:2});
    expect((await t.query(api.activities.list,{token,spaceId}))[0].status).toBe('finished');
  });
  it('keeps answers private, serializes buzzers, awards once and persists scores into the next round',async()=>{
    const {id}=await quiz();
    const friend=await t.mutation(api.room.join,{token:other,name:'Friend',look});
    await t.run(ctx=>ctx.db.patch(friend.id,{zone:spaceId,route:[{x:24.5,z:3.5}]}));
    for(const user of [token,other])await t.mutation(api.activities.play,{token:user,activityId:id,action:'join'});
    await t.mutation(api.activities.control,{token,activityId:id,action:'start'});
    const view=await t.query(api.activities.list,{token,spaceId});
    expect(JSON.stringify(view)).not.toContain('"answer":');
    const attempts=await Promise.allSettled([token,other].map(user=>t.mutation(api.activities.play,{token:user,activityId:id,action:'buzz',round:1})));
    expect(attempts.filter(x=>x.status==='fulfilled')).toHaveLength(1);
    const winner=attempts[0].status==='fulfilled'?token:other;
    await t.mutation(api.activities.play,{token:winner,activityId:id,action:'answer',round:1,choice:1});
    await expect(t.mutation(api.activities.play,{token:winner,activityId:id,action:'answer',round:1,choice:1})).rejects.toThrow();
    const ended=(await t.query(api.activities.list,{token,spaceId}))[0];
    expect(ended.status).toBe('finished');expect(ended.scores.reduce((n,p)=>n+p.score,0)).toBe(1);
    await t.mutation(api.activities.control,{token,activityId:id,action:'start'});
    expect((await t.query(api.activities.list,{token,spaceId}))[0].scores.reduce((n,p)=>n+p.score,0)).toBe(1);
    await expect(t.mutation(api.activities.play,{token:winner,activityId:id,action:'buzz',round:1})).rejects.toThrow('round');
  });
  it('rejects other hosts, unjoined players, remote players and expired rounds',async()=>{
    const {id}=await quiz();
    await t.mutation(api.room.join,{token:other,name:'Friend',look});
    await expect(t.mutation(api.activities.control,{token:other,activityId:id,action:'start'})).rejects.toThrow('host');
    await expect(t.mutation(api.activities.play,{token:other,activityId:id,action:'join'})).rejects.toThrow('space');
    await t.mutation(api.activities.control,{token,activityId:id,action:'start'});
    await expect(t.mutation(api.activities.play,{token,activityId:id,action:'buzz',round:1})).rejects.toThrow('Join');
    await t.mutation(api.activities.play,{token,activityId:id,action:'join'});
    vi.spyOn(Date,'now').mockReturnValue(Date.now()+61000);
    await t.run(ctx=>ctx.db.patch(player.id,{lastSeen:Date.now()}));
    await expect(t.mutation(api.activities.play,{token,activityId:id,action:'buzz',round:1})).rejects.toThrow('ended');
  });
  it('checks treasure distance, scores each object once and retains progress on reconnect',async()=>{
    const storageId=await t.run(ctx=>ctx.storage.store(new Blob(['sprite'])));
    const asset=await t.mutation(api.agents.createAsset,{agentToken,name:'Treasure',category:'Plants',width:1,depth:1,spriteDensity:1,icon:storageId,parts:[{storageId,direction:2,width:32,height:48,reg:{x:16,y:40}}],views:[{direction:2,source:2,mirror:false}]});
    const {itemId}=await t.mutation(api.agents.place,{agentToken,assetId:asset.id,x:25,z:3});
    const {id}=await t.mutation(api.activities.create,{agentToken,spaceId,name:'Hunt',kind:'hunt',durationSeconds:60,targets:[{itemId,clue:'Find the plant'}]});
    await t.mutation(api.activities.play,{token,activityId:id,action:'join'});
    await t.mutation(api.activities.control,{token,activityId:id,action:'start'});
    await t.run(ctx=>ctx.db.patch(player.id,{route:[{x:29.5,z:7.5}]}));
    await expect(t.mutation(api.activities.play,{token,activityId:id,action:'collect',round:1,itemId})).rejects.toThrow('closer');
    await t.run(ctx=>ctx.db.patch(player.id,{route:[{x:24.5,z:3.5}]}));
    await t.mutation(api.activities.play,{token,activityId:id,action:'collect',round:1,itemId});
    await expect(t.mutation(api.activities.play,{token,activityId:id,action:'collect',round:1,itemId})).rejects.toThrow('already');
    expect((await t.query(api.activities.list,{token,spaceId}))[0].me.found).toEqual([itemId]);
  });
});
